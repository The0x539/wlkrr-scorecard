import { BinaryReader, Decodable } from "../decode.ts";

export abstract class AssetBase extends Decodable {
  abstract readonly typeID: AssetType;
}

export class PPtr {
  fileID: number;
  pathID: number;

  constructor(r: BinaryReader) {
    this.fileID = r.i32();
    this.pathID = r.version < 14 ? r.i32() : r.i64();
  }
}

